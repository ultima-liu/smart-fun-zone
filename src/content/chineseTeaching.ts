export function getChineseTeaching(id: string): ChineseTeaching {
  const lesson = getChineseTextbookLesson(id);
  if (!lesson) throw new Error(`未知语文课：${id}`);
  const pack = getChineseTextbookStudy(id);
  const pinyinPack = CHINESE_PINYIN_STUDY[id];
  const word = pinyinPack?.words.find((item) => !item.word.includes('口形'))?.word ?? '啊';
  const oral = { ...(ORAL[id] ?? O(`用“${word}”或本课另一个词语写一句自己的话。`, `我用“${word}”说：____。`, PINYIN_EXPRESSION_MODELS[id], `请家人说一个含“${word}”的句子，先说出听到的信息，再接着回应。`, ['使用本课词语', '把词用于自己的句子', '围绕题目表达，意思清楚'])), responseModel: LISTENING_MODELS[id] };
  const goals: ChineseTeaching['goals'] = pinyinPack ? [
    { skill: 'pinyin', text: `听辨${pinyinPack.letters.map((item) => item.glyph).join('、')}相关音节，分清易混的声音与声调。` },
    { skill: 'recognition', text: `借助拼音认读本课词语，并联系它的意思。` },
    { skill: 'expression', text: '把本课词语用于自己的句子，表达清楚、完整的意思。' },
  ] : [
    { skill: pack?.recognize?.length ? 'recognition' : 'listening', text: pack?.recognize?.length ? `认读${pack.recognize.slice(0, 3).map((item) => item.char).join('、')}等本课生字，脱离拼音做抽样检查。` : `听懂本课内容，${oral.criteria[0]}。` },
    { skill: lesson.kind === 'reading' ? 'reading' : pack?.writing?.length ? 'writing' : 'reading', text: lesson.kind === 'reading' ? `${oral.prompt}联系课文说出依据或感受。` : pack?.writing?.length ? `在屏幕书写${pack.writing.map((item) => item.char).join('、')}，对照笔顺和位置检查。` : `${oral.criteria[1]}，结合画面或材料说明。` },
    { skill: 'expression', text: `${oral.criteria.join('；')}。` },
  ];
  const index = CHINESE_TEXTBOOK_LESSONS.findIndex((item) => item.id === id);
  const previous = CHINESE_TEXTBOOK_LESSONS.slice(0, index).reverse().find((item) => item.kind === lesson.kind);
  const progression = lesson.kind === 'pinyin' ? '从听辨字母与声调，到连读音节，再把新音节用于认词和交流；提示可逐步收起。'
    : lesson.kind === 'reading' ? '从完整听读、说出画面，到比较词句、表达感受，再用自己的话讲述或创作。'
      : lesson.kind === 'garden' ? '把前面学过的字词和方法用于真实倾听、回应与生活任务。'
        : lesson.kind === 'literacy' ? '从图字联系、认读单字，到换词语认字、屏幕书写，再用字词表达自己的事。'
          : '从认识学校与学习活动，到说完整句，再听懂别人并作出回应。';
  return {
    goals, progression: `${previous ? `接着《${previous.title}》继续练。` : ''}${progression}`,
    sessions: lesson.kind === 'pinyin' ? ['先听辨与看形', '再练拼读与交流'] : lesson.kind === 'garden' ? ['先学字词与积累', '再做生活交流与共读'] : pack?.writing?.length ? ['先听读与认字', '再屏幕写字与表达'] : ['先听读与观察', '再表达与应用'],
    bridge: id === 'metal-wood-water-fire-earth' ? 'required' : 'optional', oral, transfer: TRANSFER[id], reading: READING[id],
  };
}
