/** 由课文分词挑选最多 4 个主题配图 emoji（按内容命中数排序）；无匹配返回空 */
export function themeEmojis(words: string[]): string[] {
  const scores = new Map<string, number>();
  for (const w of words) {
    for (const t of THEMES) {
      if (t.keywords.some((k) => w.includes(k))) {
        scores.set(t.emoji, (scores.get(t.emoji) ?? 0) + 1);
      }
    }
  }
  return [...scores.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 4)
    .map(([e]) => e);
}
