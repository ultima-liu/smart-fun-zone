export function useI18n() {
  const lang = useStore((s) => s.lang);
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>): string => {
      let s = dict[key]?.[lang] ?? dict[key]?.zh ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.replaceAll(`{${k}}`, String(v));
        }
      }
      return s;
    },
    [lang],
  );
  return { lang, t };
}

